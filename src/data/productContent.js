// Returns the Figma content entry describing a given catalogue product, if any.
export function contentForProduct(product) {
  if (!product) return null
  return (
    PRODUCT_CONTENT.find((c) => c.match && new RegExp(c.match, c.matchFlags || 'i').test(product.title)) || null
  )
}
